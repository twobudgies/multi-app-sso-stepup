// Writes src/app/env.generated.ts from environment variables / the repo-root .env (cross-platform, no bash).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../../..');
const env = { ...process.env };
try {
  for (const line of fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (m && !(m[1] in env)) env[m[1]] = m[2];
  }
} catch { /* no .env: defaults */ }
const out = `// GENERATED by scripts/gen-env.mjs. Do not edit, do not commit.
export const ENV = ${JSON.stringify({
  IDP_PROFILE: env.IDP_PROFILE || 'keycloak',
  IDP_ISSUER: env.IDP_ISSUER || 'http://localhost:8180/realms/stepup',
  API_PORT: env.API_PORT || '5100',
  ANGULAR_PORT: env.ANGULAR_PORT || '5400',
})} as const;
`;
fs.writeFileSync(path.join(import.meta.dirname, '../src/app/env.generated.ts'), out);
console.log('env.generated.ts written');
